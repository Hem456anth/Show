    fun name(code: String): String {
        val cc = code.uppercase(Locale.ROOT)
        names[cc]?.let { return it }
        val name = Locale("", cc).getDisplayCountry(Locale.ENGLISH)
        return if (name.isBlank() || name.equals(cc, ignoreCase = true)) cc else name
    }

